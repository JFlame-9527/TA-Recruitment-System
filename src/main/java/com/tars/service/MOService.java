    /**
     * Verifies if a user is the owner of a position.
     * <p>
     * This security check ensures that only the MO who posted a position can perform
     * management operations on it (view applications, make decisions, withdraw, etc.).
     * </p>
     *
     * @param posId  ID of the position to verify
     * @param userId ID of the user claiming ownership
     * @return true if user is the position owner, false otherwise
     */
    public boolean verifyPositionOwner(String posId, String userId) {
        if (posId == null || posId.trim().isEmpty() || userId == null || userId.trim().isEmpty()) {
            log.warn("posId or userId is null or empty");
            return false;
        }

        try {
            Position position = positionRepo.getEntityById(posId);
            if (position == null) {
                log.warn("position not found, posId: {}", posId);
                return false;
            }
            return userId.equals(position.getPostUserId());
        } catch (IOException e) {
            log.error("verify position owner failed, posId: {}, userId: {}, error message: {}",
                    posId, userId, e.getMessage());
            return false;
        }
    }

    /**
     * Retrieves a TA's profile with application feedback for MO review.
     * <p>
     * This method combines TA profile information with the feedback from their application
     * to provide MOs with a complete view during the review process.
     * </p>
     *
     * @param profileId     ID of the TA profile
     * @param applicationId ID of the application (for retrieving feedback)
     * @return ProfileDTO with profile data and feedback, or null if profile not found
     * @see ProfileMapper#toMOProfileDTO(TAProfile, String)
     */
    public ProfileDTO getProfile(String profileId, String applicationId) {
        if (profileId == null || profileId.trim().isEmpty()) {
            log.warn("profile is null or empty");
            return null;
        }

        try {
            TAProfile profile = taProfileRepo.getEntityById(profileId);
            if (profile == null) {
                log.warn("profile not found, profileId: {}", profileId);
                return null;
            }
            Application application = applicationRepo.getEntityById(applicationId);
            String feedback = application != null ? application.getFeedback() : "";
            return ProfileMapper.INSTANCE.toMOProfileDTO(profile, feedback);
        } catch (IOException e) {
            log.error("get ta profile failed, profileId: {}, error message: {}", profileId, e.getMessage());
            return null;
        }
    }

    /**
     * Extends an offer to a TA applicant and updates position statistics.
     * <p>
     * This method performs the following actions:
     * <ol>
     *   <li>Validates application exists and has status=0 (applied)</li>
     *   <li>Sets application status to 1 (offered)</li>
     *   <li>Saves feedback (if provided)</li>
     *   <li>Increments position's offeredNum counter</li>
     *   <li>If offeredNum >= requiredNum, sets position status to 1 (filled)</li>
     * </ol>
     * </p>
     * <p>
     * <b>Validation:</b> Only applications with status=0 (applied) can be offered.
     * Already offered/rejected/withdrawn applications cannot be re-offered.
     * </p>
     *
     * @param appId    ID of the application to offer
     * @param feedback Optional feedback message to the TA
     * @return true if offer succeeded, false if validation failed or IO error occurred
     */
    public boolean offerApplication(String appId, String feedback) {
        if (appId == null || appId.trim().isEmpty()) {
            log.warn("appId is null or empty");
            return false;
        }

        try {
            Application application = applicationRepo.getEntityById(appId);
            if (application == null) {
                log.warn("Application not found, appId: {}", appId);
                return false;
            }

            if (application.getStatus() != 0) {
                log.warn("Application status is not 'applied', appId: {}, status: {}", appId, application.getStatus());
                return false;
            }

            application.setStatus(1);
            application.setFeedback(feedback != null ? feedback : "");
            applicationRepo.saveEntity(application);

            Position position = positionRepo.getEntityById(application.getPositionId());
            if (position != null) {
                position.setOfferedNum(position.getOfferedNum() + 1);

                if (position.getOfferedNum() >= position.getRequiredNum()) {
                    position.setStatus(1);
                }

                positionRepo.saveEntity(position);
            }

            log.info("Offer application success, appId: {}", appId);
            return true;
        } catch (IOException e) {
            log.error("Offer application failed, appId: {}, error: {}", appId, e.getMessage());
            return false;
        }
    }

