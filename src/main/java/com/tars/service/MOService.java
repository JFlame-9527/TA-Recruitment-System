    private final int appPageSize = 10;

    /**
     * Creates a new position or reposts an existing one with AI-generated portrait.
     * <p>
     * This method supports two modes:
     * </p>
     * <p>
     * <b>Normal Creation Mode (repostId is null/empty):</b>
     * <ol>
     *   <li>Generates portrait from position data using {@link PortraitGenerator}</li>
     *   <li>Sets updateAt timestamp to current time</li>
     *   <li>Saves position (new UUID auto-generated by Position constructor)</li>
     *   <li>Saves portrait</li>
     * </ol>
     * </p>
     * <p>
     * <b>Repost Mode (repostId is provided):</b>
     * <ol>
     *   <li>Loads original position by reposId</li>
     *   <li>Preserves original position ID and createAt timestamp</li>
     *   <li>Updates all other fields from the provided position object</li>
     *   <li>Generates new portrait from updated position data</li>
     *   <li>Sets updateAt to current time</li>
     *   <li>Saves position (updates existing record due to preserved ID)</li>
     *   <li>Saves new portrait</li>
     * </ol>
     * </p>
     * <p>
     * <b>Use Case for Repost:</b> When an MO wants to re-open a position from a previous
     * semester with minor changes (e.g., updated dates, adjusted requirements) while
     * maintaining the same position identity for tracking purposes.
     * </p>
     *
     * @param position Position object with all required fields set
     * @param repostId  Original position ID for repost mode, or null/empty for new creation
     * @return true if operation succeeded, false if IO error occurred or original position not found (repost mode)
     * @see PortraitGenerator#generatePortrait(Position)
     */
    public boolean postPosition(Position position, String repostId) {
        try {
            Portrait portrait = portraitGenerator.generatePortrait(position);
            position.setPortraitId(portrait.getId());

            if (repostId != null && !repostId.trim().isEmpty()) {
                // Repost mode: load original position and preserve id and createAt
                Position originalPosition = positionRepo.getEntityById(repostId);
                
                if (originalPosition == null) {
                    log.error("Original position not found for repost, reposId: {}", repostId);
                    return false;
                }

                // Preserve original id and createAt
                String originalId = originalPosition.getId();
                Timestamp originalCreateAt = originalPosition.getCreateAt();

                // Update the position with preserved fields
                position.setId(originalId);
                position.setCreateAt(originalCreateAt);
                position.setUpdateAt(Timestamp.valueOf(LocalDateTime.now()));

                // Save the reposted position (update existing record)
                positionRepo.saveEntity(position);
                
                log.info("repost position success, positionId: {}, originalCreateAt: {}", 
                        originalId, originalCreateAt);
            } else {
                // Normal create mode: generate new id and timestamps
                position.setUpdateAt(Timestamp.valueOf(LocalDateTime.now()));
                positionRepo.saveEntity(position);
                
                log.info("create position success, positionId: {}", position.getId());
            }

            // Always save/update the portrait
            portraitRepo.saveEntity(portrait);

        } catch (IOException e) {
            log.error("create/repost position failed, positionId: {}, error message: {}", 
                    position.getId(), e.getMessage());
            return false;
        }
        return true;
    }


    /**
     * Retrieves a paginated list of positions posted by an MO (basic version).
     * <p>
     * This simple version returns all positions for the MO without filtering or sorting.
     * </p>
     *
     * @param userId ID of the MO user
     * @param page   Page number (1-based, clamped to minimum 1)
     * @return List of PosBriefDTO for the requested page
     * @see PosMapper#toMOPosBriefDTO(Position)
     */
    public List<PosBriefDTO> getPositionList(String userId, int page) {
        if (userId == null || userId.trim().isEmpty()) {
            log.warn("userId is null or empty");
            return List.of();
        }

        try {
            List<Position> positions = positionRepo.loadAllEntities();

            if (positions == null || positions.isEmpty()) {
                return List.of();
            }

            int pageNum = Math.max(page, 1);

            return positions.stream()
                    .filter(pos -> pos != null && userId.equals(pos.getPostUserId()))
                    .skip((long) (pageNum - 1) * posPageSize)
                    .limit(posPageSize)
                    .map(PosMapper.INSTANCE::toMOPosBriefDTO)
                    .filter(Objects::nonNull)
                    .toList();

        } catch (IOException e) {
            log.error("get position list failed, userId: {}, error message: {}", userId, e.getMessage());
            return List.of();
        }
    }

    /**
     * Retrieves a paginated list of positions posted by an MO with filtering and sorting.
     * <p>
     * This enhanced version supports:
     * <ul>
     *   <li><b>Filtering</b>: By position status (opened/closed/filled/withdrawn)</li>
     *   <li><b>Sorting</b>: By postDate or deadline</li>
     *   <li><b>Pagination</b>: Same as basic version</li>
     * </ul>
     * </p>
     * <p>
     * <b>Filter Options:</b>
     * <ul>
     *   <li>"opened" - Positions accepting applications (status=0)</li>
     *   <li>"closed" - Positions no longer accepting (status=1, note: code uses 1 for closed but Position defines 1=filled)</li>
     *   <li>"filled" - All required TAs have been offered (status=2)</li>
     *   <li>"withdrawn" - Cancelled positions (status=3)</li>
     *   <li>Other values - No filter applied</li>
     * </ul>
     * </p>
     * <p>
     * <b>Sort Options:</b>
     * <ul>
     *   <li>"postDate" - By posting date (descending, newest first)</li>
     *   <li>"deadline" - By application deadline (ascending, earliest first)</li>
     *   <li>Other values - No sorting applied (default order)</li>
     * </ul>
     * </p>
     * <p>
     * <b>Null Handling:</b> Date comparisons use {@link Comparator#nullsLast(Comparator)}
     * to ensure positions with null dates appear at the end of sorted results.
     * </p>
     *
     * @param userId    ID of the MO user
     * @param condition Query conditions containing filter, order, and page parameters
     * @return List of PosBriefDTO for the requested page with applied filters and sorting
     * @see QueryCondition
     * @see PosMapper#toMOPosBriefDTO(Position)
     */
    public List<PosBriefDTO> getPositionList(String userId, QueryCondition condition) {
        if (userId == null || userId.trim().isEmpty()) {
            log.warn("userId is null or empty");
            return List.of();
        }

        try {
            List<Position> positions = positionRepo.loadAllEntities();

            if (positions == null || positions.isEmpty()) {
                return List.of();
            }

            int pageNum = Math.max(condition.getPage(), 1);

            Stream<Position> posStream = positions.stream()
                    .filter(pos -> pos != null && userId.equals(pos.getPostUserId()));

            posStream = switch (condition.getFilter()) {
                case "opened" -> posStream.filter(pos -> pos.getStatus() == 0);
                case "closed" -> posStream.filter(pos -> pos.getStatus() == 1);
                case "filled" -> posStream.filter(pos -> pos.getStatus() == 2);
                case "withdrawn" -> posStream.filter(pos -> pos.getStatus() == 3);
                default -> posStream;
            };

            posStream = switch (condition.getOrder()) {
                case "postDate" -> posStream.sorted(Comparator.comparing(Position::getPostDate, Comparator.nullsLast(Comparator.naturalOrder())).reversed());
                case "deadline" -> posStream.sorted(Comparator.comparing(Position::getDeadline, Comparator.nullsLast(Comparator.naturalOrder())));
                default -> posStream;
            };

            return posStream.skip((long) (pageNum - 1) * posPageSize)
                    .limit(posPageSize)
                    .map(PosMapper.INSTANCE::toMOPosBriefDTO)
                    .filter(Objects::nonNull)
                    .toList();

        } catch (IOException e) {
            log.error("get position list failed, userId: {}, error message: {}", userId, e.getMessage());
            return List.of();
        }
    }


