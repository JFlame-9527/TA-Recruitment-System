    /**
     * Generates a list of weekly period start dates spanning from startDate to endDate.
     * <p>
     * This helper method creates a list of LocalDate objects representing the start of each week
     * (Monday) within the position's duration. Used for workload validation.
     * </p>
     * <p>
     * <b>Algorithm:</b>
     * <ol>
     *   <li>Start from startDate</li>
     *   <li>Add current date to list</li>
     *   <li>Calculate days until next Sunday</li>
     *   <li>Jump to next Monday (Sunday + 1 day)</li>
     *   <li>Repeat until exceeding endDate</li>
     * </ol>
     * </p>
     *
     * @param startDate Position start date
     * @param endDate   Position end date
     * @return List of weekly period start dates (Mondays)
     */
    private List<LocalDate> generateWeeklyPeriods(LocalDate startDate, LocalDate endDate) {
        List<LocalDate> periods = new ArrayList<>();
        
        LocalDate current = startDate;
        
        while (!current.isAfter(endDate)) {
            periods.add(current);
            
            DayOfWeek currentDayOfWeek = current.getDayOfWeek();
            int daysUntilSunday = DayOfWeek.SUNDAY.getValue() - currentDayOfWeek.getValue();
            
            if (daysUntilSunday == 0) {
                daysUntilSunday = 7;
            }
            
            current = current.plusDays(daysUntilSunday + 1);
        }

        return periods;
    }

    /**
     * Checks if adding a new position would exceed a TA's maximum weekly workload.
     * <p>
     * This method performs detailed workload analysis across all weeks of the position duration:
     * <ol>
     *   <li>For each week in the position duration:
     *     <ul>
     *       <li>Calculate week boundaries (Monday to Sunday)</li>
     *       <li>Sum workload from new position + all existing offered positions overlapping that week</li>
     *       <li>If total > maxWeeklyWorkload → exceeds</li>
     *     </ul>
     *   </li>
     * </ol>
     * </p>
     * <p>
     * <b>Overlap Detection:</b> A position overlaps a week if:
     * <pre>
     * weekStart &lt;= positionEnd AND weekEnd &gt;= positionStart
     * </pre>
     * </p>
     * <p>
     * <b>Use Case:</b> Prevents TAs from being overloaded with too many positions,
     * ensuring they can maintain quality work across all commitments.
     * </p>
     *
     * @param offeredApps      List of applications where TA has been offered (status=1)
     * @param newPosition      The new position being considered
     * @param weeklyPeriods    List of weekly period start dates
     * @param maxWeeklyWorkload TA's maximum allowed weekly workload (hours)
     * @return true if workload would be exceeded in any week, false otherwise
     * @throws IOException if loading position data fails
     */
    private boolean checkWorkloadExceeds(List<Application> offeredApps, 
                                         Position newPosition,
                                         List<LocalDate> weeklyPeriods,
                                         float maxWeeklyWorkload) {
        try {
            LocalDate positionEndDate = newPosition.getEndDate().toLocalDateTime().toLocalDate();

            for (LocalDate weekStart : weeklyPeriods) {
                DayOfWeek startDayOfWeek = weekStart.getDayOfWeek();
                int daysUntilSunday = DayOfWeek.SUNDAY.getValue() - startDayOfWeek.getValue();
                
                LocalDate weekEnd = weekStart.plusDays(daysUntilSunday);
                
                if (weekEnd.isAfter(positionEndDate)) {
                    weekEnd = positionEndDate;
                }

                float totalWorkload = newPosition.getWeeklyWorkload();

                for (Application offeredApp : offeredApps) {
                    Position offeredPosition = positionRepo.getEntityById(offeredApp.getPositionId());
                    if (offeredPosition == null) {
                        continue;
                    }

                    LocalDate posStart = offeredPosition.getStartDate().toLocalDateTime().toLocalDate();
                    LocalDate posEnd = offeredPosition.getEndDate().toLocalDateTime().toLocalDate();

                    if (!weekStart.isAfter(posEnd) && !weekEnd.isBefore(posStart)) {
                        totalWorkload += offeredPosition.getWeeklyWorkload();
                    }
                }

                if (totalWorkload > maxWeeklyWorkload) {
                    return true;
                }
            }
            
            return false;
        } catch (IOException e) {
            log.error("Check workload exceeds failed, error message: {}", e.getMessage());
            return false;
        }
    }

    /**
     * Withdraws a position and cleans up all related data.
     * <p>
     * This method performs comprehensive cleanup when an MO cancels a position:
     * <ol>
     *   <li>Sets position status to 3 (withdrawn)</li>
     *   <li>Resets statistics (appliedNum=0, offeredNum=0, rejectedNum=0)</li>
     *   <li>Updates position's updateAt timestamp</li>
     *   <li>Deletes all applications for this position</li>
     *   <li>Deletes the position's portrait</li>
     * </ol>
     * </p>
     * <p>
     * <b>Impact:</b> Withdrawing a position is irreversible and removes all application history.
     * Use with caution. Consider closing (status=2) instead if you want to preserve application data.
     * </p>
     *
     * @param posId ID of the position to withdraw
     * @return true if withdrawal succeeded, false if position not found or IO error occurred
     */
    public boolean withdrawPosition(String posId) {

        try {
            Position position = positionRepo.getEntityById(posId);
            if (position == null) {
                log.warn("position not found, posId: {}", posId);
                return false;
            }

            position.setStatus(3);
            position.setAppliedNum(0);
            position.setOfferedNum(0);
            position.setRejectedNum(0);
            position.setUpdateAt(Timestamp.valueOf(LocalDateTime.now()));
            positionRepo.saveEntity(position);

            // Delete all corresponding applications
            List<Application> applications = applicationRepo.loadAllEntities();
            if (applications != null && !applications.isEmpty()) {
                for (Application app : applications) {
                    if (app != null && posId.equals(app.getPositionId())) {
                        applicationRepo.deleteEntity(app.getId());
                    }
                }
            }

            portraitRepo.deleteEntity(position.getPortraitId());

            log.info("withdraw position success, posId: {}", posId);
            return true;
        } catch (IOException e) {
            log.error("withdraw position failed, posId: {}, error message: {}", posId, e.getMessage());
            return false;
        }
    }
